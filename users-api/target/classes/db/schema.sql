-- Script de creación de la base de datos (H2 en memoria)

CREATE TABLE IF NOT EXISTS users (
    id          UUID          NOT NULL,
    name        VARCHAR(150)  NOT NULL,
    email       VARCHAR(254)  NOT NULL,
    password    VARCHAR(100)  NOT NULL,
    token       VARCHAR(1000) NOT NULL,
    created     TIMESTAMP     NOT NULL,
    modified    TIMESTAMP     NOT NULL,
    last_login  TIMESTAMP     NOT NULL,
    is_active   BOOLEAN       NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS phones (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    number  VARCHAR(30) NOT NULL,
    citycode     VARCHAR(10) NOT NULL,
    contrycode  VARCHAR(10) NOT NULL,
    user_id       UUID        NOT NULL,
    CONSTRAINT pk_phones PRIMARY KEY (id),
    CONSTRAINT fk_phones_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_phones_user ON phones (user_id);
